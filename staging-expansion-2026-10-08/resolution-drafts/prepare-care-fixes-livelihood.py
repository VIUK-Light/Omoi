def change(n,q,b=None,reason=None,perspective=None,topic=None,sensitivity=None,warnings=None):
    f=findings[n];old=by_id[f['id']];new=copy.deepcopy(old)
    c=new['card'];c['question']=q
    if b is not None:c['detail']['text']=b
    if reason is not None:new['reason']=reason
    if perspective is not None:c['perspective']=perspective
    if topic is not None:c['topic']=topic
    if sensitivity is not None:c['sensitivity']=sensitivity
    if warnings is not None:
        if warnings:c['content_warning']=warnings
        else:c.pop('content_warning',None)
    new['editorial']['peer_review_revision']={
        'reviewer':'care','finding_id':f['finding_id'],
        'note':'未承認の修正案。正本および作成担当snapshotには未適用。'}
    changes.append({'id':f['id'],'before':old,'after':new,
                    'reason':f['issue'],'addresses':[f['finding_id']]})

