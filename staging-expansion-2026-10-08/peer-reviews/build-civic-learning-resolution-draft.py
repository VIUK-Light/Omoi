proposed = {}
notes = {}

def edit(n, question=None, detail=None, reason=None, perspective=None, topic=None, remove_warning=None, note=''):
    id_ = f'exp26-learning-{n:04d}'
    after = copy.deepcopy(proposed.get(id_, before[id_]))
    c = after['card']
    if question is not None:
        c['question'] = question
    if detail is not None:
        c['detail'] = {'text': detail}
    if reason is not None:
        after['reason'] = reason
    if perspective is not None:
        c['perspective'] = perspective
    if topic is not None:
        c['topic'] = topic
    if remove_warning:
        c['content_warning'] = [x for x in c.get('content_warning', []) if x not in remove_warning]
        if not c['content_warning']:
            del c['content_warning']
    proposed[id_] = after
    notes[id_] = note

